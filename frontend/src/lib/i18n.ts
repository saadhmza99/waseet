/** Known English interface copy back to the French source, leaving everything else unchanged. */
export function frenchSource(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) return value;
  if (EN[trimmed]) return value;
  let french = REVERSE.get(trimmed);
  if (!french && trimmed === "and" && value.length <= 6) french = "et";
  if (!french && trimmed.startsWith("Subject: ")) {
    const rest = trimmed.slice("Subject: ".length);
    french = `Sujet : ${REVERSE.get(rest) || rest}`;
  }
  if (!french) return value;
  const lead = value.match(/^\s*/)?.[0] ?? "";
  const tail = value.match(/\s*$/)?.[0] ?? "";
  return `${lead}${french}${tail}`;
}

export function translateUi(language: string, value: string): string | null {
  if (language !== "English") return null;
  const trimmed = value.trim();
  if (!trimmed || trimmed.length > 280) return null;
  if (trimmed === "et" && value.length <= 6) {
    return value.replace("et", "and");
  }
  if (trimmed.startsWith("Sujet : ")) {
    const rest = EN[trimmed.slice(8)] || trimmed.slice(8);
    const lead = value.match(/^\s*/)?.[0] ?? "";
    const tail = value.match(/\s*$/)?.[0] ?? "";
    return `${lead}Subject: ${rest}${tail}`;
  }
  const next = EN[trimmed];
  if (!next || next === trimmed) return null;
  const lead = value.match(/^\s*/)?.[0] ?? "";
  const tail = value.match(/\s*$/)?.[0] ?? "";
  return `${lead}${next}${tail}`;
}
