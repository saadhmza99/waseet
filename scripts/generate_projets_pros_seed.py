#!/usr/bin/env python3
"""Generate SQL seed for projets_pros_289.csv → public.projects.

Each CSV row is a (project × professional) link. We insert one projects row per
row so each pro sees it on their portfolio (user_id = professionnel_id).

Shared Kerix projet_id is kept in attributes.source_project_id for Discover
deduping.

Run:
  python scripts/generate_projets_pros_seed.py

Output:
  supabase/seeds/seed_projets_pros_289.sql
"""

from __future__ import annotations

import csv
import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CSV = ROOT / "projets_pros_289.csv"
OUT = ROOT / "supabase" / "seeds" / "seed_projets_pros_289.sql"

SEED_BATCH = "projets_pros_289"
NS = uuid.UUID("6ba7b810-9dad-11d1-80b4-00c04fd430c8")  # UUID namespace URL

TYPE_MAP = {
    "residentiel": "projet_residentiel",
    "mixte": "projet_mixte",
    "lotissement": "lotissement",
}

PROGRESS_MAP = {
    "livre": 100,
    "pret_a_livrer": 90,
    "en_construction": 55,
    "sur_plan": 15,
    "non_determine": 0,
}


def sql_str(value: str | None) -> str:
    if value is None:
        return "NULL"
    text = str(value).replace("\r\n", "\n").replace("\r", "\n")
    return "'" + text.replace("'", "''") + "'"


def sql_num(value: str | None) -> str:
    text = (value or "").strip().replace(" ", "").replace(",", ".")
    if not text:
        return "NULL"
    try:
        float(text)
    except ValueError:
        return "NULL"
    return text


def sql_bool(value: str | None) -> str:
    return "TRUE" if str(value or "").strip().lower() in {"1", "true", "yes", "oui"} else "FALSE"


def sql_json(value) -> str:
    return sql_str(json.dumps(value, ensure_ascii=False))


def pipe_text(value: str | None) -> str | None:
    parts = [part.strip() for part in str(value or "").split("|") if part.strip()]
    return " · ".join(parts) if parts else None


def parse_gallery(raw: str | None, cover: str | None) -> list[str]:
    urls: list[str] = []
    text = (raw or "").strip()
    if text:
        try:
            parsed = json.loads(text)
            if isinstance(parsed, list):
                urls = [str(item).strip() for item in parsed if str(item).strip()]
        except json.JSONDecodeError:
            urls = []
    cover_url = (cover or "").strip()
    if cover_url and cover_url not in urls:
        urls = [cover_url, *urls]
    # de-dupe keep order
    seen: set[str] = set()
    out: list[str] = []
    for url in urls:
        if url in seen:
            continue
        seen.add(url)
        out.append(url)
    return out


def country_label(code: str | None) -> str:
    raw = (code or "").strip().upper()
    if raw in {"", "MA", "MAR", "MAROC"}:
        return "Maroc"
    return (code or "").strip() or "Maroc"


def project_row_id(projet_id: str, professionnel_id: str) -> str:
    return str(uuid.uuid5(NS, f"sifarah:project:{projet_id}:{professionnel_id}"))


def surface_label(row: dict[str, str]) -> str | None:
    lo = (row.get("superficie_min") or "").strip()
    hi = (row.get("superficie_max") or "").strip()
    unit = (row.get("unite_superficie") or "m2").strip() or "m2"
    if lo and hi and lo != hi:
        return f"{lo}–{hi} {unit}"
    if lo or hi:
        return f"{lo or hi} {unit}"
    return None


def load_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def main() -> None:
    path = DEFAULT_CSV
    if not path.exists():
        raise SystemExit(f"Missing CSV: {path}")

    rows = load_csv(path)
    if not rows:
        raise SystemExit("No project rows in CSV")

    lines: list[str] = []
    lines.append("-- AUTO-GENERATED by scripts/generate_projets_pros_seed.py")
    lines.append("-- Do not edit by hand; re-run the script after CSV updates.")
    lines.append(f"-- Seed batch: {SEED_BATCH}")
    lines.append(f"-- Source: {path.name}")
    lines.append(f"-- Rows: {len(rows)} (one projects row per professional link)")
    lines.append("-- Requires: profiles from seed_pros_services_289 already present.")
    lines.append("")
    lines.append("BEGIN;")
    lines.append("")
    lines.append(
        f"DELETE FROM public.projects WHERE attributes->>'seed_batch' = {sql_str(SEED_BATCH)};"
    )
    lines.append("")

    inserted = 0
    skipped = 0
    for row in rows:
        projet_id = (row.get("projet_id") or "").strip()
        pro_id = (row.get("professionnel_id") or "").strip()
        if not projet_id or not pro_id:
            skipped += 1
            continue

        row_id = project_row_id(projet_id, pro_id)
        title = (row.get("titre_annonce") or row.get("nom_projet") or "Projet").strip() or "Projet"
        cover = (row.get("image_principale_url") or "").strip() or None
        images = parse_gallery(row.get("images_galerie_json"), cover)
        type_raw = (row.get("type_projet") or "").strip().lower()
        project_type = TYPE_MAP.get(type_raw)
        status = (row.get("statut_construction") or "").strip() or None
        commercial = (row.get("statut_commercial") or "").strip() or None
        progress = PROGRESS_MAP.get(status or "", 0)

        attrs = {
            "seed_batch": SEED_BATCH,
            "source_project_id": projet_id,
            "source_url": (row.get("url_source") or "").strip() or None,
            "professionnel_nom": (row.get("professionnel_nom") or "").strip() or None,
            "description_courte": (row.get("description_courte") or "").strip() or None,
            "architecte": (row.get("architecte") or "").strip() or None,
            "bureau_etudes": (row.get("bureau_etudes") or "").strip() or None,
            "entreprises_construction": (row.get("entreprises_construction") or "").strip() or None,
            "sous_traitants": (row.get("sous_traitants") or "").strip() or None,
            "equipe_realisation_mentions": (row.get("equipe_realisation_mentions") or "").strip()
            or None,
            "chambres_min": (row.get("chambres_min") or "").strip() or None,
            "chambres_max": (row.get("chambres_max") or "").strip() or None,
            "nb_offres": (row.get("nb_offres") or "").strip() or None,
        }

        # Only insert when the professional profile exists (seeded pros).
        lines.append(
            "INSERT INTO public.projects ("
            "id, user_id, title, description, city, region, neighborhood, address, postal_code, country, "
            "latitude, longitude, category, project_type, status, commercial_status, progress, "
            "expected_end, actual_end, cover_image, images, typologies, equipment, nearby, "
            "price_on_request, price_from, price_min, price_max, currency, surface, "
            "promoter_id, promoter_name, promoter_website, attributes"
            ") "
            "SELECT "
            f"{sql_str(row_id)}::uuid, "
            f"{sql_str(pro_id)}::uuid, "
            f"{sql_str(title)}, "
            f"{sql_str((row.get('description') or '').strip() or None)}, "
            f"{sql_str((row.get('ville') or '').strip() or None)}, "
            "NULL, "
            f"{sql_str((row.get('quartier') or '').strip() or None)}, "
            f"{sql_str((row.get('adresse') or '').strip() or None)}, "
            f"{sql_str((row.get('code_postal') or '').strip() or None)}, "
            f"{sql_str(country_label(row.get('pays')))}, "
            f"{sql_num(row.get('latitude'))}, "
            f"{sql_num(row.get('longitude'))}, "
            f"{sql_str(type_raw or None)}, "
            f"{sql_str(project_type)}, "
            f"{sql_str(status)}, "
            f"{sql_str(commercial)}, "
            f"{progress}, "
            f"{sql_str((row.get('date_livraison_prevue') or '').strip() or None)}, "
            f"{sql_str((row.get('date_livraison_effective') or '').strip() or None)}, "
            f"{sql_str(cover)}, "
            f"{sql_json(images)}::jsonb, "
            f"{sql_str(pipe_text(row.get('typologies')))}, "
            f"{sql_str(pipe_text(row.get('equipements')))}, "
            f"{sql_str(pipe_text(row.get('proximites')))}, "
            f"{sql_bool(row.get('prix_sur_demande'))}, "
            f"{sql_num(row.get('prix_affiche_a_partir_de'))}, "
            f"{sql_num(row.get('prix_min'))}, "
            f"{sql_num(row.get('prix_max'))}, "
            f"{sql_str((row.get('devise') or 'MAD').strip() or 'MAD')}, "
            f"{sql_str(surface_label(row))}, "
            f"{sql_str((row.get('promoteur_id') or '').strip() or None)}, "
            f"{sql_str((row.get('promoteur_nom') or '').strip() or None)}, "
            f"{sql_str((row.get('promoteur_profil_url') or '').strip() or None)}, "
            f"{sql_json(attrs)}::jsonb "
            f"WHERE EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = {sql_str(pro_id)}::uuid);"
        )
        lines.append("")
        inserted += 1

    lines.append("COMMIT;")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")
    print(f"INSERT statements: {inserted} | skipped incomplete: {skipped}")
    print(f"Unique source projects: {len({(r.get('projet_id') or '').strip() for r in rows})}")
    print(f"Unique professionals: {len({(r.get('professionnel_id') or '').strip() for r in rows})}")


if __name__ == "__main__":
    main()
