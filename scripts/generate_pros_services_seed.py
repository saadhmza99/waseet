#!/usr/bin/env python3
"""Generate SQL seed for 289 Tachrone pros → auth.users + profiles + services.

Source CSVs (default):
  ../../Projects/chridari-sifarah/output/pros_services_289/

Run:
  python scripts/generate_pros_services_seed.py

Output:
  supabase/seeds/seed_pros_services_289.sql
  supabase/seeds/seed_pros_services_289_passwords.csv

Password pattern per pro: Sifarah-{username}-2026!
"""

from __future__ import annotations

import csv
import json
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PROS = Path(
    r"C:\Users\Hamza\Projects\chridari-sifarah\output\pros_services_289\professionnels_289.csv"
)
DEFAULT_SVCS = Path(
    r"C:\Users\Hamza\Projects\chridari-sifarah\output\pros_services_289\prestations_services.csv"
)
OUT = ROOT / "supabase" / "seeds" / "seed_pros_services_289.sql"
OUT_PASSWORDS = ROOT / "supabase" / "seeds" / "seed_pros_services_289_passwords.csv"

SEED_BATCH = "pros_services_289"
PASSWORD_PREFIX = "Sifarah"
PASSWORD_SUFFIX = "2026!"


def pro_password(username: str) -> str:
    """Unique placeholder password with a firm-specific middle segment."""
    return f"{PASSWORD_PREFIX}-{username}-{PASSWORD_SUFFIX}"


def sql_str(value: str | None) -> str:
    if value is None:
        return "NULL"
    text = str(value).replace("\r\n", "\n").replace("\r", "\n")
    return "'" + text.replace("'", "''") + "'"


def sql_bool(value: str | None) -> str:
    return "TRUE" if str(value or "").strip().lower() in {"1", "true", "yes", "oui"} else "FALSE"


def pipe_list(value: str | None) -> list[str]:
    if not value:
        return []
    return [part.strip() for part in str(value).split("|") if part.strip()]


def is_mission_option(value: str) -> bool:
    """CSV wrongly put National/International under options as 'Mission nationale' etc."""
    text = value.strip().lower()
    if not text:
        return False
    if text in {"national", "international"}:
        return True
    if re.match(r"^mission(s)?\s+(nationale?|internationales?|à l'international|a l'international)\b", text):
        return True
    if re.match(r"^missions?\s+internationales?\b", text):
        return True
    return False


def service_options(value: str | None) -> list[str]:
    return [item for item in pipe_list(value) if not is_mission_option(item)]


def sql_json_list(value: str | None) -> str:
    return sql_str(json.dumps(pipe_list(value), ensure_ascii=False))


def sql_json_options(value: str | None) -> str:
    return sql_str(json.dumps(service_options(value), ensure_ascii=False))


def slugify(value: str, fallback: str) -> str:
    text = unicodedata.normalize("NFKD", value or "")
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text).strip("-")
    text = re.sub(r"-{2,}", "-", text)
    return (text or fallback)[:40]


def trunc(value: str | None, n: int) -> str:
    text = (value or "").strip()
    if len(text) <= n:
        return text
    return text[: n - 1].rstrip() + "…"


def load_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def main() -> None:
    pros_path = DEFAULT_PROS
    svcs_path = DEFAULT_SVCS
    if not pros_path.exists() or not svcs_path.exists():
        raise SystemExit(f"Missing CSV files:\n  {pros_path}\n  {svcs_path}")

    pros = load_csv(pros_path)
    services = load_csv(svcs_path)
    if not pros:
        raise SystemExit("No professionals in CSV")

    usernames: set[str] = set()
    username_by_id: dict[str, str] = {}
    for row in pros:
        user_id = (row.get("id") or "").strip()
        nom = (row.get("nom") or "").strip() or f"pro-{user_id[:8]}"
        base = slugify(nom, f"pro-{user_id[:8]}")
        username = base
        n = 2
        while username in usernames:
            username = f"{base}-{n}"[:48]
            n += 1
        usernames.add(username)
        username_by_id[user_id] = username

    lines: list[str] = []
    lines.append("-- AUTO-GENERATED by scripts/generate_pros_services_seed.py")
    lines.append("-- Do not edit by hand; re-run the script after CSV updates.")
    lines.append(f"-- Seed batch: {SEED_BATCH}")
    lines.append(f"-- Password pattern: {PASSWORD_PREFIX}-{{username}}-{PASSWORD_SUFFIX}")
    lines.append(f"-- Password roster: {OUT_PASSWORDS.name}")
    lines.append(f"-- Professionals: {len(pros)} | Services: {len(services)}")
    lines.append("--")
    lines.append("-- Maps:")
    lines.append("--   professionnels_289 → auth.users + public.profiles")
    lines.append("--   profiles.internal_category_id ← internal_categories.code (NOT CSV numeric id)")
    lines.append("--   prestations_services → public.services (user_id = firmId)")
    lines.append("--")
    password_rows: list[dict[str, str]] = []
    lines.append("CREATE EXTENSION IF NOT EXISTS pgcrypto;")
    lines.append("")
    lines.append("BEGIN;")
    lines.append("")
    lines.append("-- Remove previous seed batch (safe re-run)")
    lines.append(
        f"DELETE FROM public.services WHERE user_id IN ("
        f"SELECT id FROM auth.users WHERE raw_user_meta_data->>'seed_batch' = {sql_str(SEED_BATCH)}"
        f");"
    )
    lines.append(
        f"DELETE FROM public.profile_category_history WHERE profile_id IN ("
        f"SELECT id FROM auth.users WHERE raw_user_meta_data->>'seed_batch' = {sql_str(SEED_BATCH)}"
        f");"
    )
    lines.append(
        f"DELETE FROM public.profiles WHERE id IN ("
        f"SELECT id FROM auth.users WHERE raw_user_meta_data->>'seed_batch' = {sql_str(SEED_BATCH)}"
        f");"
    )
    lines.append(
        f"DELETE FROM auth.identities WHERE user_id IN ("
        f"SELECT id FROM auth.users WHERE raw_user_meta_data->>'seed_batch' = {sql_str(SEED_BATCH)}"
        f");"
    )
    lines.append(
        f"DELETE FROM auth.users WHERE raw_user_meta_data->>'seed_batch' = {sql_str(SEED_BATCH)};"
    )
    lines.append("")

    # --- auth users (trigger creates bare profiles) ---
    lines.append("-- auth.users (+ identities). handle_new_user creates profiles.")
    for row in pros:
        user_id = (row.get("id") or "").strip()
        email = (row.get("email") or "").strip().lower()
        nom = (row.get("nom") or "").strip() or f"pro-{user_id[:8]}"
        username = username_by_id[user_id]

        password = pro_password(username)
        password_rows.append(
            {
                "id": user_id,
                "email": email,
                "username": username,
                "full_name": nom,
                "password": password,
            }
        )
        meta = {
            "seed_batch": SEED_BATCH,
            "username": username,
            "full_name": nom,
            "profession": (row.get("metier_principal") or row.get("internal_category_label") or "").strip(),
            "location": (row.get("ville") or "").strip(),
            "bio": trunc(row.get("description") or row.get("presentation_text"), 450),
            "phone": (row.get("telephone") or "").strip(),
            "profile_type": "enterprise",
            "internal_category_code": (row.get("internal_category_code") or "").strip(),
            "source_firm_id": user_id,
        }
        meta_json = sql_str(json.dumps(meta, ensure_ascii=False))

        app_meta = sql_str(json.dumps({"provider": "email", "providers": ["email"]}))
        lines.append(
            "INSERT INTO auth.users ("
            "instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, "
            "raw_app_meta_data, raw_user_meta_data, created_at, updated_at, "
            "confirmation_token, recovery_token, email_change_token_new, email_change"
            ") VALUES ("
            f"'00000000-0000-0000-0000-000000000000', {sql_str(user_id)}::uuid, "
            f"'authenticated', 'authenticated', {sql_str(email)}, "
            f"crypt({sql_str(password)}, gen_salt('bf')), NOW(), "
            f"{app_meta}::jsonb, "
            f"{meta_json}::jsonb, NOW(), NOW(), '', '', '', ''"
            ");"
        )
        lines.append(
            "INSERT INTO auth.identities ("
            "id, user_id, identity_data, provider, provider_id, last_sign_in_at, created_at, updated_at"
            ") VALUES ("
            f"{sql_str(user_id)}::uuid, {sql_str(user_id)}::uuid, "
            f"jsonb_build_object('sub', {sql_str(user_id)}, 'email', {sql_str(email)}, "
            f"'email_verified', true, 'phone_verified', false), "
            f"'email', {sql_str(user_id)}, NOW(), NOW(), NOW()"
            ");"
        )

    lines.append("")
    lines.append("-- Enrich profiles + attach internal_category by CODE")
    for row in pros:
        user_id = (row.get("id") or "").strip()
        nom = (row.get("nom") or "").strip() or f"pro-{user_id[:8]}"
        code = (row.get("internal_category_code") or "").strip()
        email = (row.get("email") or "").strip().lower()
        username = username_by_id[user_id]
        about = (row.get("presentation_text") or row.get("description") or "").strip()
        bio = trunc(row.get("description") or row.get("presentation_text"), 450)
        lines.append("UPDATE public.profiles SET")
        lines.append(f"  username = {sql_str(username)},")
        lines.append(f"  full_name = {sql_str(nom)},")
        lines.append(
            f"  profession = {sql_str((row.get('metier_principal') or row.get('internal_category_label') or '').strip())},"
        )
        lines.append(f"  location = {sql_str((row.get('ville') or '').strip())},")
        lines.append(f"  bio = {sql_str(bio)},")
        lines.append(f"  about_text = {sql_str(about) if about else 'NULL'},")
        lines.append(f"  phone = {sql_str((row.get('telephone') or '').strip() or None)},")
        lines.append(f"  email = {sql_str(email)},")
        lines.append(f"  website_url = {sql_str((row.get('site_web') or '').strip() or None)},")
        lines.append(f"  ice = {sql_str((row.get('ice') or '').strip() or None)},")
        lines.append(f"  avatar_url = {sql_str((row.get('logo_url') or '').strip() or None)},")
        lines.append(
            f"  cover_photo_url = {sql_str((row.get('presentation_image') or '').strip() or None)},"
        )
        lines.append("  profile_type = 'enterprise',")
        if code:
            lines.append(
                f"  internal_category_id = (SELECT id FROM public.internal_categories WHERE code = {sql_str(code)} LIMIT 1)"
            )
        else:
            lines.append("  internal_category_id = NULL")
        lines.append(f"WHERE id = {sql_str(user_id)}::uuid;")
        lines.append("")

    lines.append("-- services from prestations_services.csv")
    for row in services:
        svc_id = (row.get("id") or "").strip()
        firm_id = (row.get("firmId") or "").strip()
        if not svc_id or not firm_id:
            continue
        title = (row.get("title") or "").strip() or "Service"
        lines.append(
            "INSERT INTO public.services ("
            "id, user_id, title, description, category, cover, gallery, kinds, included, options, "
            "price_mode, amount, duration, zone_mode, cities, region, travel, remote, "
            "audiences, audience_other, missions"
            ") VALUES ("
            f"{sql_str(svc_id)}::uuid, {sql_str(firm_id)}::uuid, "
            f"{sql_str(title)}, "
            f"{sql_str((row.get('description') or '').strip() or None)}, "
            f"{sql_str((row.get('category') or '').strip() or None)}, "
            f"{sql_str((row.get('cover') or '').strip() or None)}, "
            f"{sql_json_list(row.get('gallery'))}::jsonb, "
            f"{sql_json_list(row.get('kinds'))}::jsonb, "
            f"{sql_json_list(row.get('included'))}::jsonb, "
            f"{sql_json_options(row.get('options'))}::jsonb, "
            f"{sql_str((row.get('priceMode') or 'devis').strip() or 'devis')}, "
            f"{sql_str((row.get('amount') or '').strip() or None)}, "
            f"{sql_str((row.get('duration') or '').strip() or None)}, "
            f"{sql_str((row.get('zoneMode') or 'villes').strip() or 'villes')}, "
            f"{sql_json_list(row.get('cities'))}::jsonb, "
            f"{sql_str((row.get('region') or '').strip() or None)}, "
            f"{sql_bool(row.get('travel'))}, {sql_bool(row.get('remote'))}, "
            f"{sql_json_list(row.get('audiences'))}::jsonb, "
            f"{sql_str((row.get('audienceOther') or '').strip() or None)}, "
            f"{sql_json_list(row.get('missions'))}::jsonb"
            ");"
        )

    lines.append("")
    lines.append("COMMIT;")
    lines.append("")
    lines.append(
        f"-- Login: email from CSV + password {PASSWORD_PREFIX}-{{username}}-{PASSWORD_SUFFIX}"
    )
    lines.append(f"-- Full roster: {OUT_PASSWORDS.name}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    with OUT_PASSWORDS.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["id", "email", "username", "full_name", "password"])
        writer.writeheader()
        writer.writerows(password_rows)
    print(f"Wrote {OUT}")
    print(f"Wrote {OUT_PASSWORDS}")
    print(f"Pros: {len(pros)} | Services: {len(services)}")
    print(f"Password pattern: {PASSWORD_PREFIX}-{{username}}-{PASSWORD_SUFFIX}")
    if password_rows:
        print(f"Example: {password_rows[0]['email']} -> {password_rows[0]['password']}")


if __name__ == "__main__":
    main()
