#!/usr/bin/env python3
"""Enrich the 15 seeded promoteurs with detailed infos from
promoteurs_immobiliers_15.csv (13 rows available; B. Saad and Philippe
Benisty have no enriched data and are left untouched).

Mapping onto public.profiles:
  description_courte -> bio (<=450 chars, fallback: description truncated)
  description        -> about_text, plus an appended "Informations" block
                        (raison sociale, siege, registre de commerce, annee de
                        creation, effectif, capital, reseaux sociaux) since
                        profiles has no dedicated columns for those
  logo_url           -> avatar_url
  images_json[0]     -> cover_photo_url
  ville_siege        -> location
  telephone (1st)    -> phone
  email              -> profiles.email (display only; auth logins untouched)
  site_web           -> website_url
  ice                -> ice

Only non-empty CSV values overwrite; empty values keep the current profile
data. Idempotent UPDATEs keyed on profiles.id (= promoteur_id).

Usage: python scripts/generate_promoteurs_infos_seed.py
"""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(ROOT, "promoteurs_immobiliers_15.csv")
OUT_PATH = os.path.join(ROOT, "supabase", "seeds", "seed_promoteurs_infos_289.sql")


def esc(v: str) -> str:
    return "'" + v.replace("'", "''") + "'"


def clean(v) -> str:
    return (v or "").strip()


SOCIAL_LABELS = [
    ("facebook_url", "Facebook"),
    ("instagram_url", "Instagram"),
    ("linkedin_url", "LinkedIn"),
    ("youtube_url", "YouTube"),
    ("autres_reseaux", "Autres réseaux"),
]


def build_about(row) -> str:
    parts = []
    desc = clean(row.get("description"))
    if desc:
        parts.append(desc)
    info = []
    legal = clean(row.get("nom_legal"))
    if legal and legal != clean(row.get("nom")):
        info.append(f"Raison sociale : {legal}")
    adresse = clean(row.get("adresse"))
    if adresse:
        info.append(f"Siège : {adresse}")
    rc = clean(row.get("registre_commerce"))
    if rc:
        info.append(f"Registre de commerce : {rc}")
    annee = clean(row.get("annee_creation"))
    if annee:
        info.append(f"Année de création : {annee}")
    effectif = clean(row.get("effectif"))
    if effectif:
        info.append(f"Effectif : {effectif}")
    capital = clean(row.get("capital"))
    if capital:
        info.append(f"Capital : {capital}")
    for key, label in SOCIAL_LABELS:
        url = clean(row.get(key))
        if url:
            info.append(f"{label} : {url}")
    if info:
        parts.append("Informations\n" + "\n".join(info))
    return "\n\n".join(parts)


def main():
    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))

    lines = [
        "-- Enrich seeded promoteurs (batch promoteurs_289) with detailed infos",
        "-- from promoteurs_immobiliers_15.csv. Generated by",
        "-- scripts/generate_promoteurs_infos_seed.py. Safe to re-run.",
        "-- Only non-empty CSV values are written; auth logins are untouched.",
        "",
    ]
    updated = 0
    for row in rows:
        pid = clean(row.get("promoteur_id"))
        if not pid:
            continue
        sets = []

        bio = clean(row.get("description_courte")) or clean(row.get("description"))
        if bio:
            sets.append(f"bio = {esc(bio[:450])}")

        about = build_about(row)
        if about:
            sets.append(f"about_text = {esc(about)}")

        logo = clean(row.get("logo_url"))
        if logo:
            sets.append(f"avatar_url = {esc(logo)}")

        images = []
        raw_imgs = clean(row.get("images_json"))
        if raw_imgs:
            try:
                images = [u for u in json.loads(raw_imgs) if u]
            except json.JSONDecodeError:
                images = []
        if images:
            sets.append(f"cover_photo_url = {esc(images[0])}")

        ville = clean(row.get("ville_siege"))
        if ville:
            sets.append(f"location = {esc(ville)}")

        tel = clean(row.get("telephone")).split("|")[0].strip()
        if tel:
            sets.append(f"phone = {esc(tel)}")

        email = clean(row.get("email"))
        if email:
            sets.append(f"email = {esc(email)}")

        web = clean(row.get("site_web"))
        if web:
            sets.append(f"website_url = {esc(web)}")

        ice = clean(row.get("ice"))
        if ice:
            sets.append(f"ice = {esc(ice)}")

        if not sets:
            continue
        sets.append("updated_at = NOW()")
        lines.append(
            f"UPDATE public.profiles SET {', '.join(sets)} WHERE id = {esc(pid)}; "
            f"-- {clean(row.get('nom'))}"
        )
        updated += 1

    lines.append("")
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT_PATH} ({updated} promoteur updates)")


if __name__ == "__main__":
    main()
