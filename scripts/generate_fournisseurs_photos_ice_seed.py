#!/usr/bin/env python3
"""Backfill avatar, cover, and ICE for Le Chantier fournisseur profiles.

Source: sifarah_supplier_photos_and_ice.csv
Match: slug from canonical_supplier_profile_url → profiles.username
       (fallback: seed_fournisseurs_289_passwords.csv by username/full_name)

Outputs: supabase/seeds/seed_fournisseurs_289_photos_ice.sql
"""
from __future__ import annotations

import csv
import json
import re
import unicodedata
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / "sifarah_supplier_photos_and_ice.csv"
PASSWORDS = ROOT / "supabase" / "seeds" / "seed_fournisseurs_289_passwords.csv"
OUT = ROOT / "supabase" / "seeds" / "seed_fournisseurs_289_photos_ice.sql"

SKIP_SLUGS = {"", "en", "pros", "fr", "profil"}


def sql_str(value: str | None) -> str:
    if value is None or value == "":
        return "NULL"
    text = str(value).replace("\r\n", "\n").replace("\r", "\n").replace("'", "''")
    return f"'{text}'"


def norm_name(value: str) -> str:
    text = unicodedata.normalize("NFKD", value or "")
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = text.lower().strip()
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def slug_from_url(url: str) -> str:
    path = urlparse((url or "").strip()).path.strip("/")
    parts = [p for p in path.split("/") if p]
    if not parts:
        return ""
    # …/en/pros/profil/{slug}
    if "profil" in parts:
        i = parts.index("profil")
        if i + 1 < len(parts):
            return parts[i + 1].lower()
    last = parts[-1].lower()
    return "" if last in SKIP_SLUGS else last


def is_http(url: str) -> bool:
    u = (url or "").strip()
    return u.startswith("http://") or u.startswith("https://")


def main() -> None:
    id_by_user: dict[str, str] = {}
    id_by_name: dict[str, str] = {}
    with PASSWORDS.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            pid = (row.get("id") or "").strip()
            user = (row.get("username") or "").strip().lower()
            name = norm_name(row.get("full_name") or "")
            if pid and user:
                id_by_user[user] = pid
            if pid and name and name not in id_by_name:
                id_by_name[name] = pid

    rows = list(csv.DictReader(CSV_PATH.open(encoding="utf-8-sig", newline="")))
    lines: list[str] = [
        "-- AUTO-GENERATED by scripts/generate_fournisseurs_photos_ice_seed.py",
        "-- Fill avatar (logo), cover (profile photo), and ICE for fournisseur profiles.",
        "-- Safe to re-run: sets values from CSV when present.",
        "BEGIN;",
        "",
    ]

    matched = 0
    skipped_no_match = 0
    skipped_empty = 0
    with_ice = 0
    with_avatar = 0
    with_cover = 0
    unmatched: list[str] = []

    for row in rows:
        name = (row.get("supplier_name") or "").strip()
        url = (row.get("canonical_supplier_profile_url") or "").strip()
        slug = slug_from_url(url)
        ice = (row.get("ice_number") or "").strip()
        logo = (row.get("company_logo_url") or "").strip()
        photo = (row.get("company_profile_photo_url") or "").strip()
        if not is_http(logo):
            logo = ""
        if not is_http(photo):
            photo = ""
        # Prefer distinct cover; if same as logo keep as cover still (better than empty)
        if not ice and not logo and not photo:
            skipped_empty += 1
            continue

        pid = id_by_user.get(slug) if slug else None
        how = "slug"
        if not pid:
            pid = id_by_name.get(norm_name(name))
            how = "name"
        if not pid:
            skipped_no_match += 1
            unmatched.append(f"{name} ({slug or url})")
            continue

        matched += 1
        sets: list[str] = []
        if ice:
            sets.append(f"  ice = {sql_str(ice)}")
            with_ice += 1
        if logo:
            sets.append(f"  avatar_url = {sql_str(logo)}")
            with_avatar += 1
        if photo:
            sets.append(f"  cover_photo_url = {sql_str(photo)}")
            with_cover += 1
        if not sets:
            skipped_empty += 1
            continue
        sets.append("  updated_at = NOW()")
        lines.append(f"-- {name} (@{slug or '?'}, match={how})")
        lines.append("UPDATE public.profiles SET")
        lines.append(",\n".join(sets))
        lines.append(f"WHERE id = {sql_str(pid)}::uuid;")
        lines.append("")

    lines.append("COMMIT;")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Wrote {OUT}")
    print(f"matched={matched} ice={with_ice} avatar={with_avatar} cover={with_cover}")
    print(f"skipped_empty={skipped_empty} skipped_no_match={skipped_no_match}")
    if unmatched:
        print("unmatched:")
        for u in unmatched[:30]:
            print(" ", u)
        if len(unmatched) > 30:
            print(f"  … +{len(unmatched) - 30} more")


if __name__ == "__main__":
    main()
