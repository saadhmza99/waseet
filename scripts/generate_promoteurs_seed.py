#!/usr/bin/env python3
"""Generate SQL seed for promoteurs → auth.users + profiles + cloned projects.

Source CSV (repo root): promoteurs_projets_289.csv
  promoteur_id, promoteur_nom, promoteur_profil_url,
  projet_ids (pipe-separated Kerix ids = projects.attributes.source_project_id)

Run:
  python scripts/generate_promoteurs_seed.py

Output:
  supabase/seeds/seed_promoteurs_289.sql
  supabase/seeds/seed_promoteurs_289_passwords.csv

Each promoteur gets a real account (same pattern as the pros seed,
password Sifarah-{username}-2026!) and one cloned projects row per
Kerix project (id = uuid5(URL_NS, "sifarah:project:{sid}:{promoteur_id}")),
owned by the promoteur so their profile Projects section is populated.
Documents are fanned out onto the cloned rows as well.

Emails: contact@<company domain> when the profile URL is the company's
own site, otherwise {username}@sifarah.local (placeholder, confirmed).
"""

from __future__ import annotations

import csv
import json
import re
import unicodedata
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / "promoteurs_projets_289.csv"
OUT = ROOT / "supabase" / "seeds" / "seed_promoteurs_289.sql"
OUT_PASSWORDS = ROOT / "supabase" / "seeds" / "seed_promoteurs_289_passwords.csv"

SEED_BATCH = "promoteurs_289"
PASSWORD_PREFIX = "Sifarah"
PASSWORD_SUFFIX = "2026!"
PROFESSION = "Promotion immobilière"
INTERNAL_CATEGORY_CODE = "1.2.1"  # Promoteur immobilier
NS = uuid.UUID("6ba7b810-9dad-11d1-80b4-00c04fd430c8")  # UUID namespace URL
AGGREGATOR_DOMAINS = {"chridari.ma", "tachrone.ma", "www.chridari.ma", "www.tachrone.ma"}

PROJECT_COLUMNS = [
    "title", "description", "city", "region", "neighborhood", "address",
    "postal_code", "country", "latitude", "longitude", "category", "subtype",
    "project_type", "status", "commercial_status", "progress", "start_date",
    "expected_end", "actual_end", "cover_image", "images", "typologies",
    "equipment", "nearby", "price_on_request", "price_from", "price_min",
    "price_max", "currency", "usage", "land_area", "built_area", "buildings",
    "floors", "basements", "apartments", "parking", "surface", "promoter_id",
    "promoter_name", "promoter_website", "team", "partners", "phases",
    "updates", "media", "units", "choices", "attributes",
]


def sql_str(value: str | None) -> str:
    if value is None:
        return "NULL"
    text = str(value).replace("\r\n", "\n").replace("\r", "\n")
    return "'" + text.replace("'", "''") + "'"


def slugify(value: str, fallback: str) -> str:
    text = unicodedata.normalize("NFKD", value or "")
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text).strip("-")
    text = re.sub(r"-{2,}", "-", text)
    return (text or fallback)[:40].strip("-")


def pipe_list(value: str | None) -> list[str]:
    if not value:
        return []
    return [part.strip() for part in str(value).split("|") if part.strip()]


def email_for(username: str, url: str) -> str:
    match = re.search(r"https?://([^/]+)", url or "")
    domain = match.group(1).lower() if match else ""
    if domain and domain not in AGGREGATOR_DOMAINS:
        return f"contact@{domain.removeprefix('www.')}"
    return f"{username}@sifarah.local"


def main() -> None:
    if not CSV_PATH.exists():
        raise SystemExit(f"Missing CSV: {CSV_PATH}")
    with CSV_PATH.open(encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise SystemExit("No promoteurs in CSV")

    usernames: set[str] = set()
    prepared: list[dict] = []
    for row in rows:
        promoteur_id = (row.get("promoteur_id") or "").strip()
        nom = (row.get("promoteur_nom") or "").strip() or f"promoteur-{promoteur_id[:8]}"
        base = slugify(nom, f"promoteur-{promoteur_id[:8]}")
        username = base
        n = 2
        while username in usernames:
            username = f"{base}-{n}"[:48]
            n += 1
        usernames.add(username)
        url = (row.get("promoteur_profil_url") or "").strip()
        project_ids = pipe_list(row.get("projet_ids"))
        prepared.append(
            {
                "id": promoteur_id,
                "nom": nom,
                "username": username,
                "email": email_for(username, url),
                "url": url,
                "project_ids": project_ids,
                "password": f"{PASSWORD_PREFIX}-{username}-{PASSWORD_SUFFIX}",
            }
        )

    batch_users = (
        f"(SELECT id FROM auth.users WHERE raw_user_meta_data->>'seed_batch' = {sql_str(SEED_BATCH)})"
    )

    lines: list[str] = []
    lines.append("-- AUTO-GENERATED by scripts/generate_promoteurs_seed.py")
    lines.append("-- Do not edit by hand; re-run the script after CSV updates.")
    lines.append(f"-- Seed batch: {SEED_BATCH}")
    lines.append(f"-- Password pattern: {PASSWORD_PREFIX}-{{username}}-{PASSWORD_SUFFIX}")
    lines.append(f"-- Password roster: {OUT_PASSWORDS.name}")
    lines.append(f"-- Promoteurs: {len(prepared)} | Projects: {sum(len(p['project_ids']) for p in prepared)}")
    lines.append("--")
    lines.append("-- Maps:")
    lines.append("--   promoteurs_projets_289 → auth.users + public.profiles (Promotion immobilière, code 1.2.1)")
    lines.append("--   projet_ids → cloned public.projects rows owned by the promoteur")
    lines.append("--")
    lines.append("CREATE EXTENSION IF NOT EXISTS pgcrypto;")
    lines.append("")
    lines.append("BEGIN;")
    lines.append("")
    lines.append("-- Remove previous seed batch (safe re-run)")
    lines.append(f"DELETE FROM public.projects WHERE user_id IN {batch_users};")
    lines.append(f"DELETE FROM public.profile_category_history WHERE profile_id IN {batch_users};")
    lines.append(f"DELETE FROM public.profiles WHERE id IN {batch_users};")
    lines.append(f"DELETE FROM auth.identities WHERE user_id IN {batch_users};")
    lines.append(f"DELETE FROM auth.users WHERE raw_user_meta_data->>'seed_batch' = {sql_str(SEED_BATCH)};")
    lines.append("")

    lines.append("-- auth.users (+ identities). handle_new_user creates profiles.")
    for p in prepared:
        meta = {
            "seed_batch": SEED_BATCH,
            "username": p["username"],
            "full_name": p["nom"],
            "profession": PROFESSION,
            "location": "",
            "bio": f"Promoteur immobilier au Maroc — {len(p['project_ids'])} projet(s) référencé(s) sur Sifarah.",
            "profile_type": "enterprise",
            "internal_category_code": INTERNAL_CATEGORY_CODE,
            "source_promoteur_id": p["id"],
        }
        app_meta = sql_str(json.dumps({"provider": "email", "providers": ["email"]}))
        lines.append(
            "INSERT INTO auth.users ("
            "instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, "
            "raw_app_meta_data, raw_user_meta_data, created_at, updated_at, "
            "confirmation_token, recovery_token, email_change_token_new, email_change"
            ") VALUES ("
            f"'00000000-0000-0000-0000-000000000000', {sql_str(p['id'])}::uuid, "
            f"'authenticated', 'authenticated', {sql_str(p['email'])}, "
            f"crypt({sql_str(p['password'])}, gen_salt('bf')), NOW(), "
            f"{app_meta}::jsonb, {sql_str(json.dumps(meta, ensure_ascii=False))}::jsonb, NOW(), NOW(), '', '', '', ''"
            ");"
        )
        lines.append(
            "INSERT INTO auth.identities ("
            "id, user_id, identity_data, provider, provider_id, last_sign_in_at, created_at, updated_at"
            ") VALUES ("
            f"{sql_str(p['id'])}::uuid, {sql_str(p['id'])}::uuid, "
            f"jsonb_build_object('sub', {sql_str(p['id'])}, 'email', {sql_str(p['email'])}, "
            "'email_verified', true, 'phone_verified', false), "
            f"'email', {sql_str(p['id'])}, NOW(), NOW(), NOW()"
            ");"
        )

    lines.append("")
    lines.append("-- Enrich profiles + attach internal_category by CODE")
    for p in prepared:
        bio = f"Promoteur immobilier au Maroc — {len(p['project_ids'])} projet(s) référencé(s) sur Sifarah."
        lines.append("UPDATE public.profiles SET")
        lines.append(f"  username = {sql_str(p['username'])},")
        lines.append(f"  full_name = {sql_str(p['nom'])},")
        lines.append(f"  profession = {sql_str(PROFESSION)},")
        lines.append(f"  bio = {sql_str(bio)},")
        lines.append(f"  about_text = {sql_str(bio)},")
        lines.append(f"  email = {sql_str(p['email'])},")
        lines.append(f"  website_url = {sql_str(p['url']) if p['url'] else 'NULL'},")
        lines.append("  profile_type = 'enterprise',")
        lines.append(
            f"  internal_category_id = (SELECT id FROM public.internal_categories WHERE code = {sql_str(INTERNAL_CATEGORY_CODE)} LIMIT 1)"
        )
        lines.append(f"WHERE id = {sql_str(p['id'])}::uuid;")
        lines.append("")

    lines.append("-- Clone one projects row per (promoteur, Kerix project), owned by the promoteur")
    select_cols = []
    for col in PROJECT_COLUMNS:
        if col == "promoter_name":
            select_cols.append(None)  # placeholder, replaced per promoteur below
        elif col == "promoter_website":
            select_cols.append(None)
        else:
            select_cols.append(f"src.{col}")
    for p in prepared:
        cols_sql = ", ".join(PROJECT_COLUMNS)
        for sid in p["project_ids"]:
            new_id = str(uuid.uuid5(NS, f"sifarah:project:{sid}:{p['id']}"))
            selects = []
            for col, expr in zip(PROJECT_COLUMNS, select_cols):
                if col == "promoter_name":
                    selects.append(sql_str(p["nom"]))
                elif col == "promoter_website":
                    selects.append(sql_str(p["url"]) if p["url"] else "src.promoter_website")
                else:
                    selects.append(expr)
            lines.append(
                f"INSERT INTO public.projects (id, user_id, {cols_sql})\n"
                f"SELECT {sql_str(new_id)}::uuid, {sql_str(p['id'])}::uuid, {', '.join(selects)}\n"
                "FROM (SELECT * FROM public.projects "
                f"WHERE attributes->>'source_project_id' = {sql_str(sid)} "
                "ORDER BY created_at ASC LIMIT 1) src;"
            )
    lines.append("")

    lines.append("-- Fan the source projects' documents out onto the cloned rows")
    lines.append(
        "INSERT INTO public.projects_documents (project_id, title, type, url, privacy, position)\n"
        "SELECT DISTINCT np.id, d.title, d.type, d.url, d.privacy, d.position\n"
        "FROM public.projects np\n"
        "JOIN public.projects op\n"
        "  ON op.attributes->>'source_project_id' = np.attributes->>'source_project_id' AND op.id <> np.id\n"
        "JOIN public.projects_documents d ON d.project_id = op.id\n"
        f"WHERE np.user_id IN {batch_users}\n"
        "  AND NOT EXISTS (\n"
        "    SELECT 1 FROM public.projects_documents x WHERE x.project_id = np.id AND x.url = d.url\n"
        "  );"
    )
    lines.append("")

    lines.append("-- Profile city = most frequent city across the promoteur's projects")
    lines.append(
        "UPDATE public.profiles p SET location = (\n"
        "  SELECT pr.city FROM public.projects pr\n"
        "  WHERE pr.user_id = p.id AND pr.city IS NOT NULL AND pr.city <> ''\n"
        "  GROUP BY pr.city ORDER BY count(*) DESC LIMIT 1\n"
        ")\n"
        f"WHERE p.id IN {batch_users}\n"
        "  AND EXISTS (SELECT 1 FROM public.projects pr WHERE pr.user_id = p.id AND pr.city IS NOT NULL AND pr.city <> '');"
    )
    lines.append("")
    lines.append("COMMIT;")
    lines.append("")
    lines.append(f"-- Login: email in roster + password {PASSWORD_PREFIX}-{{username}}-{PASSWORD_SUFFIX}")
    lines.append(f"-- Full roster: {OUT_PASSWORDS.name}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    with OUT_PASSWORDS.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["id", "email", "username", "full_name", "password"])
        writer.writeheader()
        writer.writerows(
            {
                "id": p["id"],
                "email": p["email"],
                "username": p["username"],
                "full_name": p["nom"],
                "password": p["password"],
            }
            for p in prepared
        )
    total_projects = sum(len(p["project_ids"]) for p in prepared)
    print(f"Wrote {OUT}")
    print(f"Wrote {OUT_PASSWORDS}")
    print(f"Promoteurs: {len(prepared)} | Projects: {total_projects}")
    print(f"Example: {prepared[0]['email']} -> {prepared[0]['password']} (@{prepared[0]['username']})")


if __name__ == "__main__":
    main()
